/** 규칙 스위치 세 개 */
export interface Rules {
  /** 할인 후 금액으로 세는가 */
  afterDiscount: boolean
  /** 배송비를 넣는가 */
  withShip: boolean
  /** 취소·환불 주문을 넣는가 */
  withCancelled: boolean
}

export const GROSS_RULE: Rules = { afterDiscount: false, withShip: true, withCancelled: true }
export const NET_RULE: Rules = { afterDiscount: true, withShip: false, withCancelled: false }

/** 주문 한 건이 이 규칙에서 세는 금액(세지 않으면 null) */
export const countedAmount = (o: Order4, r: Rules): number | null => {
  if (!r.withCancelled && o.status !== '완료') return null
  return o.price + (r.withShip ? o.ship : 0) - (r.afterDiscount ? o.disc : 0)
}
export const totalOf = (r: Rules) => ORDERS.reduce((a, o) => a + (countedAmount(o, r) ?? 0), 0)
const same = (a: Rules, b: Rules) => a.afterDiscount === b.afterDiscount && a.withShip === b.withShip && a.withCancelled === b.withCancelled
/** 이름 있는 정의인지 */
export const nameOf = (r: Rules): { name: string; owner: string } | null =>
  same(r, GROSS_RULE) ? { name: '총매출', owner: '소라' } : same(r, NET_RULE) ? { name: '순매출', owner: '민재' } : null

